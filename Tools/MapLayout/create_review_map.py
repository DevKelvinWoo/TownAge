"""Create an isolated layout-tool review map. Never edit an existing production map."""
import json
import uuid
from pathlib import Path
import unreal

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'Saved/MapLayout'
OUT.mkdir(parents=True, exist_ok=True)
MAP = '/Game/Maps/Tools/L_MapLayout_Review01'
exists = unreal.EditorAssetLibrary.does_asset_exist(MAP)
resume = unreal.SystemLibrary.parse_param(unreal.SystemLibrary.get_command_line(), 'MapLayoutResumeReview')
if exists and not resume:
    raise RuntimeError('Review map already exists; refusing to overwrite: ' + MAP)
if exists and (OUT / 'creation_report.json').exists():
    raise RuntimeError('Completed review maps cannot be regenerated by this script.')
levels = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
assert levels.load_level(MAP) if exists else levels.new_level(MAP)
if exists:
    allowed = ('WorldSettings', 'Brush', 'DefaultPhysicsVolume')
    foreign = [a.get_actor_label() for a in actors.get_all_level_actors()
               if not a.get_actor_label().startswith('MapLayoutReview_') and a.get_class().get_name() not in allowed]
    assert not foreign, 'Refusing to resume a map with foreign actors: ' + str(foreign)


def spawn(cls, label, location, rotation=unreal.Rotator()):
    matches = [a for a in actors.get_all_level_actors() if a.get_actor_label() == label]
    assert len(matches) <= 1
    actor = matches[0] if matches else actors.spawn_actor_from_class(cls, location, rotation)
    assert isinstance(actor, cls)
    actor.set_actor_label(label)
    return actor

floor = spawn(unreal.StaticMeshActor, 'MapLayoutReview_Ground', unreal.Vector(0, 0, -25))
floor.static_mesh_component.set_static_mesh(unreal.load_asset('/Engine/BasicShapes/Cube'))
floor.set_actor_scale3d(unreal.Vector(100, 100, .5))
floor.static_mesh_component.set_collision_profile_name('BlockAll')

sun = spawn(unreal.DirectionalLight, 'MapLayoutReview_Sun', unreal.Vector(0, 0, 2000), unreal.Rotator(-45, -30, 0))
sun.get_editor_property('light_component').set_mobility(unreal.ComponentMobility.MOVABLE)
sun.get_editor_property('light_component').set_editor_property('intensity', 10.0)
sun.get_editor_property('light_component').set_editor_property('atmosphere_sun_light', True)
sky = spawn(unreal.SkyLight, 'MapLayoutReview_SkyFill', unreal.Vector(0, 0, 1500))
sky_light = sky.get_editor_property('light_component')
sky_light.set_mobility(unreal.ComponentMobility.MOVABLE)
sky_light.set_editor_property('source_type', unreal.SkyLightSourceType.SLS_SPECIFIED_CUBEMAP)
sky_light.set_editor_property('cubemap', unreal.load_asset('/Engine/MapTemplates/Sky/DaylightAmbientCubemap'))
spawn(unreal.SkyAtmosphere, 'MapLayoutReview_Atmosphere', unreal.Vector())
spawn(unreal.PlayerStart, 'MapLayoutReview_Start', unreal.Vector(-4200, 2500, 100))

plan = spawn(unreal.TownAgeMapLayout, 'MapLayoutReview_Plan', unreal.Vector())
snapshot = json.loads(unreal.TownAgeMapEditorLibrary.export_json(plan))


def element(kind, type_id, label, points, width=400, height=300):
    return {'id': uuid.uuid5(uuid.NAMESPACE_URL, 'townage:layout-review:' + label).hex,
            'label': label, 'kind': kind, 'typeId': type_id,
            'points': [{'x': x, 'y': y, 'z': z} for x, y, z in points],
            'widthCm': width, 'heightCm': height}


snapshot['elements'] = [
    element('Road', 'road.path', 'Main route', [(-4000, 0, 0), (0, 0, 0), (0, 3500, 0)]),
    element('Road', 'road.stone', 'Southern road', [(-3700, -3300, 0), (3500, -3300, 0)], 300),
    element('Field', 'field.soil', 'Vegetable field', [(-3500, -2500, 0), (-1000, -600, 0)]),
    element('Field', 'field.orchard', 'Orchard area', [(800, -2300, 0), (3200, -500, 0)]),
    element('Building', 'building.house', 'Home A', [(-2400, 700, 0), (-1400, 1500, 0)], height=500),
    element('Building', 'building.shop', 'Village shop', [(1000, 600, 0), (2400, 1700, 0)], height=450),
    element('Building', 'building.house', 'Home B', [(-3300, 2100, 0), (-2400, 2900, 0)], height=400),
]
result = unreal.TownAgeMapEditorLibrary.import_json(plan, json.dumps(snapshot))
assert unreal.TownAgeMapEditorLibrary.get_generated_instance_count(plan) == 9, repr(result)
exported = unreal.TownAgeMapEditorLibrary.export_json(plan)
(OUT / 'review_layout.json').write_text(exported, encoding='utf-8')
world = unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem).get_editor_world()
world.get_world_settings().set_editor_property('default_game_mode', unreal.TownAgeGameMode)
unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem).set_level_viewport_camera_info(
    unreal.Vector(0, -100, 10000), unreal.Rotator(-90, -90, 0))
assert levels.save_current_level()
(OUT / 'creation_report.json').write_text(json.dumps({'map': MAP, 'elements': 7, 'instances': 9,
                                                    'types': len(snapshot['types']), 'passed': True}, indent=2), encoding='utf-8')
print('MAP_LAYOUT_REVIEW_CREATED')
